// Command genexports writes types_gen.go: an exported alias in package
// invoist for every API schema type that oapi-codegen generated into
// internal/generated, and a re-export of every enum value.
//
// It runs as the second step of scripts/generate.sh, so a schema added to
// openapi.yaml shows up in the public package without anyone editing a
// list by hand. Operation plumbing (parameter structs, request and
// response bodies) is left out: the hand-written client in the root
// package covers those with its own, more convenient types.
//
// Usage (from the module root):
//
//	go run ./internal/cmd/genexports
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
	"strings"
)

const (
	source = "internal/generated/types.go"
	target = "types_gen.go"
)

// renames gives inline (anonymous) schemas, which oapi-codegen names
// Parent_Field, a name that reads well in Go.
var renames = map[string]string{
	"BillChainMember_Warnings": "BillWarning",
	"BillDetail_Chain":         "BillChain",
	"BillsStats_Senders":       "BillsStatsSender",
	"BillsStats_TopSenders":    "BillsStatsTopSender",
	"BillsStats_Totals":        "BillsStatsTotal",
	"BillsStats_Trend":         "BillsStatsMonth",
	"Usage_ByDay":              "UsageDay",
}

// skipped names generated schema types the public package leaves out.
// (Type aliases, which oapi-codegen emits for path parameters such as
// DocumentID and for shared responses such as NotFound, are skipped too.)
var skipped = map[string]bool{
	"Error": true, // the error envelope; failures surface as *InvoistError
}

// operationSuffixes mark types that belong to one operation's request or
// response rather than to a schema.
var operationSuffixes = []string{
	"Params",
	"JSONBody",
	"JSONBodyStatus",
	"JSONRequestBody",
	"MultipartBody",
	"MultipartRequestBody",
	"JSONResponseBody",
	"JSONResponseBodyDuplicate",
}

func exported(name string) (string, bool) {
	if skipped[name] {
		return "", false
	}
	for _, suffix := range operationSuffixes {
		if strings.HasSuffix(name, suffix) {
			return "", false
		}
	}
	if alias, ok := renames[name]; ok {
		return alias, true
	}
	if strings.Contains(name, "_") {
		log.Fatalf("%s: inline schema %s has no entry in renames", source, name)
	}
	return name, true
}

type typeAlias struct {
	alias, name, doc string
}

type enumGroup struct {
	typ    string
	values []string
}

func main() {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, source, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	var aliases []typeAlias
	var enums []enumGroup
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		switch gen.Tok {
		case token.TYPE:
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if ts.Assign.IsValid() {
					continue // a parameter or response alias, not a schema
				}
				alias, ok := exported(ts.Name.Name)
				if !ok {
					continue
				}
				doc := gen.Doc
				if ts.Doc != nil {
					doc = ts.Doc
				}
				aliases = append(aliases, typeAlias{alias: alias, name: ts.Name.Name, doc: describe(alias, ts.Name.Name, doc)})
			}
		case token.CONST:
			var group enumGroup
			for _, spec := range gen.Specs {
				vs := spec.(*ast.ValueSpec)
				ident, ok := vs.Type.(*ast.Ident)
				if !ok {
					continue
				}
				if _, ok := exported(ident.Name); !ok {
					continue
				}
				for _, name := range vs.Names {
					// A `null` inside an enum comes out as the value "<nil>";
					// in Go a nil pointer already says that.
					if strings.HasSuffix(name.Name, "LessThanNil") {
						continue
					}
					group.typ = ident.Name
					group.values = append(group.values, name.Name)
				}
			}
			if group.typ != "" {
				enums = append(enums, group)
			}
		}
	}
	slices.SortFunc(aliases, func(a, b typeAlias) int { return strings.Compare(a.alias, b.alias) })
	slices.SortFunc(enums, func(a, b enumGroup) int { return strings.Compare(a.typ, b.typ) })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/cmd/genexports from internal/generated/types.go. DO NOT EDIT.\n\n")
	buf.WriteString("package invoist\n\nimport \"github.com/invoisthq/invoist-go/internal/generated\"\n\n")
	buf.WriteString("// The API's schemas, generated from openapi.yaml.\n\n")
	for _, a := range aliases {
		fmt.Fprintf(&buf, "%s\ntype %s = generated.%s\n\n", a.doc, a.alias, a.name)
	}
	for _, e := range enums {
		alias, _ := exported(e.typ)
		fmt.Fprintf(&buf, "// The values of %s the API documents. Compare against these; a newer\n// API may send a value this version does not list.\nconst (\n", alias)
		for _, v := range e.values {
			fmt.Fprintf(&buf, "\t%s = generated.%s\n", v, v)
		}
		buf.WriteString(")\n\n")
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("formatting %s: %v\n%s", target, err, buf.Bytes())
	}
	if err := os.WriteFile(target, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// describe turns oapi-codegen's comment ("Bill One bill in a household's
// list.", or "X defines model for X.") into a Go doc comment that starts
// with the exported name.
func describe(alias, name string, doc *ast.CommentGroup) string {
	text := ""
	if doc != nil {
		text = strings.Join(strings.Fields(doc.Text()), " ")
	}
	text = strings.TrimPrefix(text, name)
	text = strings.TrimSpace(text)
	schema := strings.ReplaceAll(name, "_", ".")
	if rest, ok := strings.CutPrefix(text, "defines model for "); ok {
		schema = strings.TrimSuffix(rest, ".")
		text = ""
	}
	line := fmt.Sprintf("%s is the API's %s schema.", alias, schema)
	if text != "" {
		line += " " + text
	}
	return wrap(line)
}

func wrap(s string) string {
	var lines []string
	var cur strings.Builder
	for _, word := range strings.Fields(s) {
		if cur.Len() > 0 && cur.Len()+1+len(word) > 76 {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteByte(' ')
		}
		cur.WriteString(word)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return "// " + strings.Join(lines, "\n// ")
}
